import { describe, it, expect } from 'vitest';
import { toGcode, arcTestGcode, type Post } from '../src/core/gcode';
import { MACHINES, machineDef, parseMachine, hasMachine } from '../src/core/machines';
import type { Toolpath } from '../src/core/types';

const cut = (d: number, name: string): Toolpath => ({
  name, tool: { type: 'flat', diameter: d }, feed: 800, plungeFeed: 300,
  cuts: [{ moves: [{ x: 1, y: 1, z: 0 }, { x: 10, y: 1, z: -1 }] }],
} as unknown as Toolpath);
const job = [cut(6, 'a'), cut(3, 'b')];
const post = (flavor: string, more: Partial<Post> = {}): Post => ({ flavor, spindle: 'manual', safeZ: 5, decimals: 3, ...more });
const lines = (flavor: string, more: Partial<Post> = {}) => toGcode(job, post(flavor, more)).split('\n');

describe('machine definitions', () => {
  it('ships Marlin and GRBL first, then the rest', () => {
    const ids = MACHINES.map(m => m.id);
    expect(ids.slice(0, 2)).toEqual(['marlin', 'grbl']);
    for (const id of ['grblhal', 'linuxcnc', 'mach3', 'uccnc', 'generic']) expect(ids).toContain(id);
    expect(hasMachine('marlin')).toBe(true);
    expect(hasMachine('nope')).toBe(false);
    expect(machineDef('nope').id).toBe('marlin');
  });
  it('reads a PureCutCNC style file and fills in what it leaves out', () => {
    const d = parseMachine({
      id: 'x1', name: 'X', fileExtension: '.ngc', program: { header: ['( {programName} )', 'G17'], commentPrefix: '(', commentSuffix: ')', lineNumbers: true, lineNumberIncrement: 5 },
      toolChange: { commands: ['M6 T{toolNumber}'], pauseCommand: 'M1' }, stop: { programEndCommand: 'M30' }, motion: { arcInterpolation: true },
    });
    expect(d.extension).toBe('ngc');
    expect(d.header).toEqual(['( {programName} )', 'G17', '{unitsCommand}', 'G90']); // units and absolute mode are never left out
    expect(d.lineStep).toBe(5);
    expect(d.arcs).toBe(true);
    expect(d.spindle).toBe('manual');
    expect(JSON.stringify(d)).not.toContain('M1"'); // their pause command is not used: a bit change must always stop
  });
  it('rejects a file with no usable id or name', () => {
    expect(() => parseMachine({ name: 'X' })).toThrow(/id/);
    expect(() => parseMachine({ id: 'a b', name: 'X' })).toThrow(/id/);
    expect(() => parseMachine({ id: 'ok' })).toThrow(/name/);
    expect(() => parseMachine(null)).toThrow();
  });
});

describe('writing for other controllers', () => {
  it('LinuxCNC: its header, bracket comments, M6 with a tool number, M2 at the end', () => {
    const g = lines('linuxcnc', { spindle: 'm3', spindleRpm: 12000 });
    expect(g[0]).toBe('( open-cam job )');
    expect(g[1]).toBe('G90 G17 G40 G49 G80 G94');
    expect(g[2]).toBe('G21');
    expect(g[3]).toBe('G54');
    expect(g.some(l => l.startsWith(';'))).toBe(false); // every comment is in brackets
    expect(g).toContain('M3 S12000');
    const i = g.findIndex(l => l === 'M6 T2');
    expect(i).toBeGreaterThan(0);
    expect(g[i - 1]).toBe('M5');
    expect(g[i + 1]).toBe('G43 H2');
    expect(g.filter(l => l.includes('M0'))).toEqual([]); // its own tool change, no plain pause
    expect(g[g.length - 2]).toBe('M2');
  });
  it('Mach3: line numbers on code lines only, a closing M30, brackets cannot nest', () => {
    const g = lines('mach3', { spindle: 'm3' });
    const code = g.filter(l => l !== '' && !l.startsWith('('));
    expect(code[0]).toBe('N10 G90 G94 G17 G40 G49 G80');
    expect(code[1]).toBe('N20 G21');
    expect(code.every(l => /^N\d+ /.test(l))).toBe(true);
    expect(g[g.length - 2]).toMatch(/^N\d+ M30$/);
    const t = toGcode(job, post('mach3', { toolChange: { mode: 'move' }, spindle: 'm3' }));
    for (const l of t.split('\n').filter(l => l.includes('('))) expect((l.match(/\(/g) ?? []).length).toBe(1);
  });
  it('grblHAL ends with its own retract and M30', () => {
    const g = lines('grblhal', { spindle: 'm3' });
    expect(g.slice(-4, -1)).toEqual(['M5', 'G0 G53 Z0', 'M30']);
  });
  it('generic stops for a bit change with M0', () => {
    const g = lines('generic', { spindle: 'm3' });
    expect(g.some(l => l.startsWith('M0 '))).toBe(true);
  });
  it('a note stays a comment in the controller\'s own style', () => {
    const g = lines('linuxcnc', { note: 'Zero is the lower-left corner.' });
    expect(g).toContain('(Zero is the lower-left corner.)');
  });
  it('the arc test uses the controller\'s own comments and end', () => {
    const t = arcTestGcode('linuxcnc').split('\n');
    expect(t.some(l => l.startsWith(';'))).toBe(false);
    expect(t[t.length - 2]).toBe('M2');
    expect(arcTestGcode('marlin')).toContain('M117 Arc test');
  });
  it('Marlin and GRBL are unchanged', () => {
    const m = lines('marlin');
    expect(m.slice(0, 5)).toEqual(['; Generated by open-cam', '; Units: mm, absolute. Work zero: X/Y at your chosen origin, Z=0 at TOP of stock.', 'G21', 'G90', 'G17']);
    expect(m).toContain('M117 Start the router');
    expect(m.filter(l => l.startsWith('G0 ')).every(l => / F\d+$/.test(l))).toBe(true);
    expect(lines('grbl').slice(-2, -1)).toEqual(['M2']);
    expect(lines('grbl').some(l => l.startsWith('M117'))).toBe(false);
  });
});
